#!/usr/bin/env python3
"""Print validation metrics and plot logged model-vs-Gazebo trajectories."""
import argparse
import csv
import math
import os
from collections import defaultdict


def rms(values):
    values = list(values)
    return math.sqrt(sum(v * v for v in values) / len(values)) if values else float("nan")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", help="CSV generated by kinematic_validation_node")
    parser.add_argument("--no-plot", action="store_true", help="Only print summary metrics")
    args = parser.parse_args()
    if not os.path.isfile(args.csv):
        raise SystemExit(f"CSV not found: {args.csv}")

    with open(args.csv, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    groups = defaultdict(list)
    for row in rows:
        groups[row["test"]].append(row)

    print("\nKinematic validation — active-motion RMSE (versus Gazebo ground truth)")
    print("Test                         Command-model XY   Wheel-rate-model XY   Wheel-odom XY   Command yaw   Wheel-model yaw")
    print("---------------------------  -----------------  --------------------  -------------  ------------  ---------------")
    for name, data in groups.items():
        active = [r for r in data if r.get("motion_active") == "1"]
        vals = lambda field: [float(r[field]) for r in active if r.get(field, "") != ""]
        print(f"{name:27}  {rms(vals('cmd_pos_error_m')):8.3f} m         "
              f"{rms(vals('wheel_model_pos_error_m')):8.3f} m        "
              f"{rms(vals('odom_pos_error_m')):8.3f} m     "
              f"{math.degrees(rms(vals('cmd_yaw_error_rad'))):8.2f} deg   "
              f"{math.degrees(rms(vals('wheel_model_yaw_error_rad'))):8.2f} deg")

    if args.no_plot:
        return
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib is not installed; skipping plots. Install python3-matplotlib or pass --no-plot.")
        return

    out_base = os.path.splitext(os.path.abspath(args.csv))[0]
    for name, data in groups.items():
        t = [float(r["case_time"]) for r in data]
        fig, axes = plt.subplots(3, 1, figsize=(10, 12), constrained_layout=True)
        axes[0].plot([float(r["gt_x_m"]) for r in data], [float(r["gt_y_m"]) for r in data], label="Gazebo ground truth", linewidth=2)
        axes[0].plot([float(r["cmd_model_x_m"]) for r in data], [float(r["cmd_model_y_m"]) for r in data], label="Command-integrated model", linestyle="--")
        axes[0].plot([float(r["wheel_model_x_m"]) for r in data], [float(r["wheel_model_y_m"]) for r in data], label="Measured-wheel-rate model", linestyle="-.")
        axes[0].plot([float(r["odom_x_m"]) for r in data], [float(r["odom_y_m"]) for r in data], label="diff_drive_controller odom", linestyle=":")
        axes[0].set_title(f"{name}: trajectory relative to test start")
        axes[0].set_xlabel("x (m)"); axes[0].set_ylabel("y (m)"); axes[0].axis("equal"); axes[0].grid(True); axes[0].legend()

        axes[1].plot(t, [float(r["cmd_pos_error_m"]) for r in data], label="Command model vs truth")
        axes[1].plot(t, [float(r["wheel_model_pos_error_m"]) for r in data], label="Wheel-rate model vs truth")
        axes[1].plot(t, [float(r["odom_pos_error_m"]) for r in data], label="Encoder odom vs truth")
        axes[1].set_ylabel("Position error (m)"); axes[1].grid(True); axes[1].legend()

        axes[2].plot(t, [float(r["cmd_v_mps"]) for r in data], label="Command v (m/s)")
        axes[2].plot(t, [float(r["wheel_kinematic_v_mps"]) for r in data], label="Measured-wheel model v (m/s)")
        axes[2].plot(t, [float(r["odom_v_mps"]) for r in data], label="Odom v (m/s)")
        axes[2].plot(t, [float(r["cmd_w_radps"]) for r in data], label="Command yaw rate (rad/s)")
        axes[2].plot(t, [float(r["wheel_kinematic_w_radps"]) for r in data], label="Measured-wheel model yaw rate (rad/s)")
        axes[2].plot(t, [float(r["odom_w_radps"]) for r in data], label="Odom yaw rate (rad/s)")
        axes[2].set_xlabel("Time since test start (s)"); axes[2].set_ylabel("Velocity"); axes[2].grid(True); axes[2].legend(ncol=2)
        path = f"{out_base}_{name}.png"
        fig.savefig(path, dpi=150)
        plt.close(fig)
        print(f"Saved plot: {path}")


if __name__ == "__main__":
    main()
